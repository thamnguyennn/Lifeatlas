# Pull outlines for the zodiac and planet symbols out of DejaVu Sans (free licence, glyph shapes may be reused)
# and write them as normalised SVG paths, so the site looks the same on every device and needs no symbol font.
import subprocess, json, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

path = subprocess.check_output(["fc-match", "-f", "%{file}", "DejaVu Sans:charset=2648"]).decode()
font = TTFont(path)
cmap = font.getBestCmap()
gs = font.getGlyphSet()

names = {
  "aries": 0x2648, "taurus": 0x2649, "gemini": 0x264A, "cancer": 0x264B, "leo": 0x264C, "virgo": 0x264D,
  "libra": 0x264E, "scorpio": 0x264F, "sagittarius": 0x2650, "capricorn": 0x2651, "aquarius": 0x2652, "pisces": 0x2653,
  "sun": 0x2609, "moon": 0x263D, "mars": 0x2642, "mercury": 0x263F, "jupiter": 0x2643, "venus": 0x2640, "saturn": 0x2644,
  "rahu": 0x260A, "ketu": 0x260B,
}
out = {}
for k, cp in names.items():
    gn = cmap[cp]
    bp = BoundsPen(gs); gs[gn].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    w, h = x1 - x0, y1 - y0
    s = 80.0 / max(w, h)                       # fit into an 80-unit box inside a 100x100 view
    ox = 50 - (w * s) / 2 - x0 * s
    oy = 50 + (h * s) / 2 + y0 * s              # flip y (font y goes up)
    pen = SVGPathPen(gs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    tp = TransformPen(pen, (s, 0, 0, -s, ox, oy))
    gs[gn].draw(tp)
    out[k] = pen.getCommands()
ts = "// Generated by scripts/extract_glyphs.py from DejaVu Sans (Bitstream Vera licence). Normalised to a 100x100 box.\n"
ts += "export const GLYPH_PATHS: Record<string, string> = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
open("/home/claude/atlas2/src/ui/glyph-paths.ts", "w").write(ts)
print(path, len(ts), "bytes", len(out), "glyphs")
